"""Render the inspectable trail of every agent run on every task (artifacts/vas-trail/<task>/<run>.jsonl) to Markdown.

For each task: what the reviewer must read (Spec.lean: assumptions, data, goal_ statements) and what Lean checked
(the accepted proof body), with line counts; then every checker call in order with its outcome and first error.
Only measured quantities: checker calls, Lean wall seconds, lines and bytes. No reviewer-time estimate.

Run: python3 src/vas_trail.py [--out docs/preprint/trail.md]
"""
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
TASKS = ROOT / "tasks"
TRAIL = ROOT / "artifacts/vas-trail"


def code_lines(text):
    """non-blank lines outside comments"""
    text = re.sub(r"/-.*?-/", "", text, flags=re.S)
    return sum(1 for ln in text.splitlines() if ln.strip() and not ln.strip().startswith("--"))


def body_of(lean_file, spec):
    """the agent's body inside a checked file: between `open Task` and the first verifier_ theorem"""
    text = (ROOT / lean_file).read_text()
    start = text.index("open Task\n") + len("open Task\n")
    end = text.index("theorem verifier_")
    return text[start:end].strip() + "\n"


def summarize(tasks=TASKS, trail=TRAIL):
    rows = []
    for tdir in sorted(p for p in tasks.iterdir() if (p / "task.json").exists()):
        task = tdir.name
        meta = json.loads((tdir / "task.json").read_text())
        spec = (tdir / "Spec.lean").read_text()
        goals = re.findall(r"^def goal_[^\n]*(?:\n  [^\n]*)*", spec, re.M)
        runs = []
        for f in sorted((trail / task).glob("*.jsonl")):
            if f.stem.startswith(("negative", "recheck", "codex-audit", "codex-review", "claude-audit", "recheck2")):
                continue
            calls = [json.loads(ln) for ln in f.read_text().splitlines()]
            acc = next((c for c in calls if c.get("ok")), None)
            manifest = ROOT / "artifacts/vas-agent-runs" / task / f.stem / "manifest.json"
            agent_wall = json.loads(manifest.read_text())["wall_s"] if manifest.exists() else None
            runs.append({"run": f.stem, "calls": calls, "accepted": acc, "agent_wall_s": agent_wall,
                         "calls_to_accept": (acc["seq"] + 1) if acc else None,
                         "lean_wall_s": round(sum(c.get("wall_s", 0) for c in calls), 1),
                         "body": body_of(acc["lean_file"], spec) if acc else None})
            rf = trail / task / f"recheck-{f.stem}.jsonl"
            runs[-1]["recheck"] = (all(json.loads(ln)["ok"] for ln in rf.read_text().splitlines())
                                   if rf.exists() else None)
        rows.append({"task": task, "title": meta["title"], "required": meta["required"], "spec": spec,
                     "spec_lines": code_lines(spec), "goal_lines": sum(g.count("\n") + 1 for g in goals), "runs": runs})
    return rows


def render(rows, drafts=()):
    out = ["# VAS candidate runs: the inspectable trail", "",
           "Generated by src/vas_trail.py from artifacts/vas-trail. A run is PASSED only if the checker returned ok "
           "(Lean exit 0, every required theorem and its verifier_ copy reported by `#print axioms`, only "
           "propext / Classical.choice / Quot.sound). Line counts are non-blank, non-comment Lean lines.", "",
           "Re-checked: the accepted body was submitted again from scratch (run recheck-<run>). Agent wall s: the whole agent "
           "run (src/vas_agent.py manifest), '-' for the overnight runs made before the runner existed.", "",
           "| task | run | status | checker calls (to accept / total) | Lean wall s | agent wall s | re-checked | reviewer reads: Spec lines (goal lines) | Lean checked: proof lines |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in list(rows) + [dict(d, task=d["task"] + " (agent-drafted card)") for d in drafts]:
        for run in r["runs"] or [{"run": "-", "calls": [], "accepted": None, "calls_to_accept": None, "lean_wall_s": 0, "body": None}]:
            st = "PASSED" if run["accepted"] else ("FAILED/UNFINISHED" if run["calls"] else "not run")
            out.append(f"| {r['task']} | {run['run']} | {st} | {run['calls_to_accept'] or '-'} / {len(run['calls'])} | "
                       f"{run['lean_wall_s']} | {run.get('agent_wall_s') or '-'} | {dict([(True, 'yes'), (False, 'NO'), (None, '-')])[run.get('recheck')]} | {r['spec_lines']} ({r['goal_lines']}) | "
                       f"{code_lines(run['body']) if run['body'] else '-'} |")
    for r in list(rows) + [dict(d, task=d["task"] + " (agent-drafted card, tasks-drafts/)") for d in drafts]:
        out += ["", f"## {r['task']}: {r['title']}", "", "### What the reviewer reads (Spec.lean)",
                "", "```lean", r["spec"].rstrip(), "```"]
        for run in r["runs"]:
            out += ["", f"### Run {run['run']}", "", "| # | time | Lean wall s | outcome | first error |", "|---|---|---|---|---|"]
            for c in run["calls"]:
                if c.get("ok"):
                    o, e = "ok", ""
                elif c.get("stage") == "contract":
                    o, e = "rejected before Lean", c.get("error", "")
                else:
                    o = f"Lean exit {c.get('exit_code')}" + (f", axioms {c['unexpected_axioms']}" if c.get("unexpected_axioms") else "")
                    e = (c.get("errors") or [""])[0]
                    e = re.sub(r"^.*?\.lean:", "line ", e)
                out.append(f"| {c['seq']} | {c['time'][11:19]} | {c.get('wall_s', 0)} | {o} | {e[:160].replace('|', '/')} |")
            if run["body"]:
                out += ["", f"Accepted body ({run['accepted']['lean_file']}):", "", "```lean", run["body"].rstrip(), "```"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    rows = summarize()
    drafts = summarize(ROOT / "tasks-drafts", ROOT / "artifacts/vas-trail-drafts") if (ROOT / "tasks-drafts").exists() else []
    md = render(rows, drafts)
    if "--out" in sys.argv:
        (ROOT / sys.argv[sys.argv.index("--out") + 1]).write_text(md)
    else:
        print(md[:4000])
